#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────────────
# EduCore ERP — Secret generator
#
# Usage (writes ready-to-paste lines to stdout):
#   bash infra/scripts/generate-secrets.sh
#
# Append directly to .env:
#   bash infra/scripts/generate-secrets.sh >> .env
#
# Requirements: openssl (installed on every Linux/macOS/WSL system)
# ──────────────────────────────────────────────────────────────────────────────
set -euo pipefail

if ! command -v openssl &>/dev/null; then
  echo "ERROR: openssl not found. Install it and retry." >&2
  exit 1
fi

ACCESS_SECRET=$(openssl rand -base64 48)
REFRESH_SECRET=$(openssl rand -base64 48)
DB_PASSWORD=$(openssl rand -base64 24 | tr -dc 'a-zA-Z0-9' | head -c 32)

echo "# Generated by infra/scripts/generate-secrets.sh on $(date -u '+%Y-%m-%d %H:%M UTC')"
echo "JWT_ACCESS_SECRET=${ACCESS_SECRET}"
echo "JWT_REFRESH_SECRET=${REFRESH_SECRET}"
echo "DB_PASSWORD=${DB_PASSWORD}"
